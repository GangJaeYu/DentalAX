/** 실제 사용 시작(데모 없이 첫 설정·초기화 후)에 넣는 기본 서식: 전화 응대 스크립트·문자 템플릿 */
function starter(ctx) {
  const a = ctx.users.admin || null;
  seed({ ...ctx, users: { ...ctx.users, manager: a, admin: a, hyg1: a, desk: a, nurse: a } });
}

module.exports = { seed, starter };
